"""Subset Source Han Serif into the web fonts the design system ships.

Outputs, in src/ds/fonts/:
  serif-ui-600.woff2, serif-ui-900.woff2  every character in our own source; always loaded
  serif-names-600.woff2                   charset-names.txt minus the UI set; loaded only
                                          when a name from the game needs it
  fonts.css                               @font-face rules for the three files
  subset.json                             what went in, for --check and for review

Text read from the game is set at weight 600, because only 600 has the names subset.

Usage:
  python -I scripts/fonts/subset.py           build
  python -I scripts/fonts/subset.py --check   fail if source text has characters the UI subset lacks
"""
import hashlib
import json
import pathlib
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
OUT = SRC / "ds" / "fonts"
SOURCE_FONTS = ROOT / "assets-src" / "fonts" / "source"
NAMES = ROOT / "assets-src" / "fonts" / "charset-names.txt"
MANIFEST = OUT / "subset.json"

WEIGHTS = {600: "SourceHanSerifCN-SemiBold.otf", 900: "SourceHanSerifCN-Heavy.otf"}
EXTRA = "，。：；！？（）“”‘’—–−·、…《》「」『』【】０１２３４５６７８９×÷±°"
SOURCE_SUFFIXES = {".ts", ".tsx", ".css"}
# Development-only sources (the mock bridge) never reach the desktop app.
DEV = SRC / "app" / "dev"


def ui_characters() -> str:
    chars = set(EXTRA)
    chars.update(chr(c) for c in range(0x20, 0x7F))
    for path in SRC.rglob("*"):
        if path.suffix in SOURCE_SUFFIXES and OUT not in path.parents and DEV not in path.parents:
            chars.update(path.read_text(encoding="utf-8"))
    return "".join(sorted(c for c in chars if c.isprintable()))


def unicode_range(chars: str) -> str:
    points = sorted({ord(c) for c in chars})
    ranges, start, prev = [], points[0], points[0]
    for p in points[1:] + [None]:
        if p is not None and p == prev + 1:
            prev = p
            continue
        ranges.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
        if p is not None:
            start = prev = p
    return ", ".join(ranges)


def subset(font: pathlib.Path, text: str, out: pathlib.Path) -> int:
    from fontTools import subset as ft_subset

    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".txt", delete=False) as fh:
        fh.write(text)
        text_file = pathlib.Path(fh.name)
    try:
        ft_subset.main([
            str(font),
            f"--text-file={text_file}",
            "--flavor=woff2",
            "--no-hinting",
            "--desubroutinize",
            f"--output-file={out}",
        ])
    finally:
        text_file.unlink()
    return out.stat().st_size


def build() -> None:
    missing = [n for n in WEIGHTS.values() if not (SOURCE_FONTS / n).exists()]
    if missing:
        sys.exit(f"missing {', '.join(missing)}; run `npm run fonts:fetch` first")
    OUT.mkdir(parents=True, exist_ok=True)

    ui = ui_characters()
    names = "".join(sorted(set(NAMES.read_text(encoding="utf-8")) - set(ui)))

    sizes = {}
    for weight, name in WEIGHTS.items():
        sizes[f"serif-ui-{weight}.woff2"] = subset(SOURCE_FONTS / name, ui, OUT / f"serif-ui-{weight}.woff2")
    sizes["serif-names-600.woff2"] = subset(SOURCE_FONTS / WEIGHTS[600], names, OUT / "serif-names-600.woff2")

    # The names face is declared first with no unicode-range; the UI faces are declared after
    # with an exact range. Characters in the UI set never touch the names file, and the
    # browser only fetches the names file when a character outside the UI set shows up.
    ui_range = unicode_range(ui)
    css = [
        "/* Generated by scripts/fonts/subset.py. Source Han Serif CN, SIL OFL 1.1. */",
        "@font-face {",
        "  font-family: 'W3 Serif';",
        "  src: url('./serif-names-600.woff2') format('woff2');",
        "  font-weight: 600;",
        "  font-display: swap;",
        "}",
    ]
    for weight in WEIGHTS:
        css += [
            "",
            "@font-face {",
            "  font-family: 'W3 Serif';",
            f"  src: url('./serif-ui-{weight}.woff2') format('woff2');",
            f"  font-weight: {weight};",
            "  font-display: block;",
            f"  unicode-range: {ui_range};",
            "}",
        ]
    (OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")

    MANIFEST.write_text(json.dumps({
        "ui_characters": len(ui),
        "names_characters": len(names),
        "ui_sha256": hashlib.sha256(ui.encode("utf-8")).hexdigest(),
        "sizes": sizes,
        "ui": ui,
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    for name, size in sizes.items():
        print(f"{name}: {size / 1024:.0f} KB")
    print(f"UI characters: {len(ui)}, names characters: {len(names)}")


def check() -> None:
    if not MANIFEST.exists():
        sys.exit("fonts not built; run `npm run fonts`")
    built = set(json.loads(MANIFEST.read_text(encoding="utf-8"))["ui"])
    needed = set(ui_characters())
    missing = sorted(needed - built)
    if missing:
        sys.exit(f"{len(missing)} character(s) missing from the UI font subset: "
                 f"{''.join(missing[:40])}; run `npm run fonts`")
    print(f"font subset ok ({len(built)} UI characters)")


if __name__ == "__main__":
    check() if "--check" in sys.argv[1:] else build()
