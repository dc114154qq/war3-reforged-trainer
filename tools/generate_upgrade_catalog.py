"""Generate all editor-native upgrade IDs from pinned client tables and text."""
from pathlib import Path
import argparse,base64,hashlib,json,sys,zlib
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from tools.generate_forsaken_equipment_catalog import slk
from tools.generate_war3_id_descriptions import clean_text,values_from
from war3_map_objects import profile,plain_text

def generate(source,destination,audit):
    native={r['upgradeid']:r for r in slk(source/'zhCN/UpgradeData.slk')}
    entries={code:dict(rawcode=code) for code in sorted(native)}
    sources={}
    races={'human':('人类','Human'),'orc':('兽人','Orc'),'undead':('亡灵','Undead'),
           'nightelf':('暗夜精灵','Night Elf'),'naga':('娜迦','Naga'),'other':('其他','Other')}
    for locale in ('zhCN','enUS'):
        folder=source/locale;rows={};values=values_from(folder)
        for path in sorted(folder.glob('*UpgradeStrings.txt')):
            sources[locale+'/'+path.name]=hashlib.sha256(path.read_bytes()).hexdigest()
            for code,fields in profile(path.read_bytes()).items():rows.setdefault(code,{}).update(fields)
        sources[locale+'/UpgradeData.slk']=hashlib.sha256((folder/'UpgradeData.slk').read_bytes()).hexdigest()
        lang='zh' if locale=='zhCN' else 'en'
        for code,entry in entries.items():
            fields=rows.get(code,{})
            names=[plain_text(n) for n in fields.get('name',[]) if n and n not in ('_','-')]
            if not names:raise ValueError('Missing stock upgrade name: '+locale+'/'+code)
            entry['name_'+lang]=' / '.join(dict.fromkeys(names))
            parts=[];partial=False
            for i,text in enumerate(fields.get('ubertip',[]) or fields.get('tip',[])):
                cleaned,missing=clean_text(text,values);partial=partial or bool(missing)
                if cleaned:parts.append((f'{i+1}级：' if lang=='zh' else f'Level {i+1}: ')+cleaned)
            level=native[code].get('maxlevel','1')
            parts.append(('最高等级：' if lang=='zh' else 'Maximum level: ')+level)
            entry['description_'+lang]='\n'.join(parts)
            entry['description_partial']=entry.get('description_partial',False) or partial
            race=native[code].get('race','other')
            entry['category_'+lang]=races.get(race,('其他','Other'))[0 if lang=='zh' else 1]
    for entry in entries.values():entry['description_source']='魔兽争霸 III 3.0.1.24371 编辑器自带科技资料'
    encoded=base64.b85encode(zlib.compress(json.dumps(list(entries.values()),ensure_ascii=False,separators=(',',':')).encode(),9)).decode()
    code='"""All native editor upgrades, generated by tools/generate_upgrade_catalog.py."""\nimport base64,json,zlib\nfrom functools import lru_cache\nSOURCE_SHA256 = '+repr(sources)+'\n_DATA=(\n'
    code+=''.join('    '+repr(encoded[i:i+110])+'\n' for i in range(0,len(encoded),110))
    code+=')\n@lru_cache(1)\ndef entries():\n    return tuple(json.loads(zlib.decompress(base64.b85decode(_DATA))))\n'
    destination.write_text(code,encoding='utf-8')
    audit.write_text(json.dumps(dict(count=len(entries),ids=list(entries),sources=sources),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('Native upgrades:',len(entries))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('destination',type=Path);p.add_argument('audit',type=Path);a=p.parse_args();generate(a.source,a.destination,a.audit)
