"""Generate pinned editor field metadata and bilingual stock profile text."""
from pathlib import Path
import argparse,base64,hashlib,json,sys,zlib
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from tools.generate_forsaken_equipment_catalog import slk,sections
from war3_map_objects import profile


def generate(source,destination):
    data=dict(schema=1,game_build='3.0.1.24371',metadata={},profiles={},files={},sources={})
    for locale in ('zhCN','enUS'):
        folder=source/locale;labels=sections(folder/'WorldEditStrings.txt').get('WorldEditStrings',{})
        def label(key):
            seen=set()
            while key.startswith('WESTRING_') and key in labels and key not in seen:
                seen.add(key);key=labels[key].strip('"')
            return key
        for kind,name in [('ability','AbilityMetaData.slk'),('unit','UnitMetaData.slk'),('item','UnitMetaData.slk')]:
            rows=slk(folder/name)
            if kind=='item':rows=[r for r in rows if r.get('useItem')=='1']
            elif kind=='unit':rows=[r for r in rows if any(r.get(k)=='1' for k in ('useUnit','useHero','useBuilding'))]
            for row in rows:
                field=row.get('ID') or row.get('id')
                if not field:continue
                stored=data['metadata'].setdefault(kind,{}).setdefault(field,{k:v for k,v in row.items() if k not in ('ID','displayName')})
                stored[locale]=label(row.get('displayName',field))
        kinds={k:{} for k in ('item','ability','unit')}
        for path in sorted(folder.glob('*Strings.txt')):
            name=path.name
            kind=('ability' if 'Ability' in name else 'unit' if 'Unit' in name else 'item' if name.startswith('Item') else None)
            if not kind:continue
            parsed=profile(path.read_bytes())
            for code,fields in parsed.items():
                if len(code)==4:kinds[kind].setdefault(code,{}).update(fields)
            data['files'][name]=kind
        data['profiles'][locale]=kinds
        for path in folder.iterdir():
            if path.name.endswith(('MetaData.slk','Strings.txt')):
                data['sources'][locale+'/'+path.name]=hashlib.sha256(path.read_bytes()).hexdigest()
    raw=json.dumps(data,ensure_ascii=False,separators=(',',':')).encode()
    encoded=base64.b85encode(zlib.compress(raw,9)).decode()
    code='''"""Pinned editor metadata and stock text, generated by generate_map_catalog_reference.py."""\nimport base64,json,zlib\nfrom functools import lru_cache\n_DATA=(\n'''
    code+=''.join('    '+repr(encoded[i:i+110])+'\n' for i in range(0,len(encoded),110))
    code+='\n)\n@lru_cache(1)\ndef reference():\n    return json.loads(zlib.decompress(base64.b85decode(_DATA)))\n'
    destination.write_text(code,encoding='utf8')
    return dict(bytes=len(raw),compressed=len(encoded),metadata={k:len(v) for k,v in data['metadata'].items()},sources=data['sources'])

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('destination',type=Path);p.add_argument('--audit',type=Path);a=p.parse_args()
    report=generate(a.source,a.destination)
    if a.audit:a.audit.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print({k:v for k,v in report.items() if k!='sources'})
