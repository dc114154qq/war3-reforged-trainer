// Builds src/ds/icons/generated.ts from assets-src/icons/manifest.json.
// Only the listed glyphs end up in the bundle; unknown ids and malformed custom files fail the build.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const require = createRequire(resolve(root, 'package.json'))
const manifest = JSON.parse(readFileSync(resolve(root, 'assets-src/icons/manifest.json'), 'utf8'))
const gameIcons = JSON.parse(readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'))

const toCurrentColor = body => body.replace(/fill="(#000|#000000|black)"/g, 'fill="currentColor"')

function load(source, name) {
  const [kind, id] = source.split(':')
  if (kind === 'game-icons') {
    const icon = gameIcons.icons[id]
    if (!icon) throw new Error(`${name}: game-icons has no "${id}"`)
    const w = icon.width ?? gameIcons.width, h = icon.height ?? gameIcons.height
    if (w !== 512 || h !== 512) throw new Error(`${name}: expected 512x512, got ${w}x${h}`)
    return toCurrentColor(icon.body)
  }
  if (kind === 'custom') {
    const svg = readFileSync(resolve(root, 'assets-src/icons/custom', id), 'utf8')
    if (!/viewBox="0 0 512 512"/.test(svg)) throw new Error(`${name}: custom icon must use viewBox="0 0 512 512"`)
    const inner = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)
    if (!inner) throw new Error(`${name}: cannot read ${id}`)
    return toCurrentColor(inner[1].replace(/\s*\n\s*/g, ''))
  }
  throw new Error(`${name}: unknown source "${source}"`)
}

const bodies = {}
const sources = {}
const groups = {}
for (const [group, icons] of Object.entries(manifest.groups)) {
  groups[group] = Object.keys(icons)
  for (const [name, source] of Object.entries(icons)) {
    if (bodies[name]) throw new Error(`duplicate icon name "${name}"`)
    bodies[name] = load(source, name)
    sources[name] = source
  }
}

const out = `// Generated by scripts/icons/build.mjs from assets-src/icons/manifest.json. Do not edit.
export const ICON_BODIES = ${JSON.stringify(bodies, null, 2)} as const

export type IconName = keyof typeof ICON_BODIES

export const ICON_GROUPS: Record<string, IconName[]> = ${JSON.stringify(groups, null, 2)}

export const ICON_SOURCES: Record<IconName, string> = ${JSON.stringify(sources, null, 2)}

/** Required by CC BY 3.0; show on the About page. */
export const ICON_ATTRIBUTION = '部分图标来自 game-icons.net，作者 Lorc、Delapouite 等，按 CC BY 3.0 许可使用。'
`
mkdirSync(resolve(root, 'src/ds/icons'), { recursive: true })
writeFileSync(resolve(root, 'src/ds/icons/generated.ts'), out)
const kb = (Buffer.byteLength(out) / 1024).toFixed(0)
console.log(`icons: ${Object.keys(bodies).length} in ${Object.keys(groups).length} groups (${kb} KB)`)
