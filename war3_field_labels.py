def ability_field_name(spec: AbilityFieldSpec, language: str = 'zh') -> str:
    names = ABILITY_FIELD_NAMES.get(spec.rawcode)
    if names:
        return names[1 if language == 'en' else 0]
    # Keep future, uncatalogued fields identifiable rather than guessing a meaning.
    return spec.field_name or spec.constant_name or spec.rawcode


def item_field_name(spec: ItemFieldSpec, language: str = 'zh') -> str:
    names = ITEM_FIELD_NAMES.get(spec.rawcode)
    return names[1 if language == 'en' else 0] if names else spec.name or spec.rawcode


def ability_field_search_text(spec: AbilityFieldSpec) -> str:
    return ' '.join((spec.rawcode, spec.constant_name, spec.field_name,
                     spec.display_name, spec.category, spec.metadata_type,
                     *ABILITY_FIELD_NAMES.get(spec.rawcode, ()),
                     _ABILITY_SEARCH_ALIASES.get(spec.rawcode, ''))).casefold()


def item_field_search_text(spec: ItemFieldSpec) -> str:
    return ' '.join((spec.rawcode, spec.value_kind, spec.name,
                     *ITEM_FIELD_NAMES.get(spec.rawcode, ()))).casefold()
